#!/usr/bin/env python3
"""Summarise every stored baseline into HISTORY.md — the record of Synid versions
on this benchmark (accuracy per tier, and per failure trigger).

    python3 benchmarks/synid/history.py
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from score import metrics, pct, read_cases, read_run  # noqa: E402

OUT = HERE / "HISTORY.md"


def main() -> int:
    cases = read_cases()
    tiers, tags = defaultdict(list), defaultdict(list)
    for cid, c in cases.items():
        tiers[c["tier"]].append(cid)
        for t in filter(None, c["tags"].split(";")):
            tags[t].append(cid)
    runs = []
    for p in sorted((HERE / "baselines").glob("*.jsonl")):
        meta, ans = read_run(p)
        runs.append((meta, ans))
    runs.sort(key=lambda r: r[0].get("date", "") or r[0].get("label", ""))
    tag_names = sorted(tags, key=lambda t: -len(tags[t]))
    lines = ["# Synid on the benchmark — history", "",
             "Generated by `python3 benchmarks/synid/history.py` from `baselines/*.jsonl` "
             f"({len(cases)} cases: gold {len(tiers['gold'])}, silver {len(tiers['silver'])}). "
             "Accuracy = exactly one syntax, and an accepted one (README.md).", "",
             "| run | Synid commit | gold | gold, weighted | silver | " + " | ".join(tag_names) + " |",
             "|---|---|---:|---:|---:|" + "---:|" * len(tag_names)]
    for meta, ans in runs:
        g = metrics(cases, ans, tiers["gold"], weighted=True)
        s = metrics(cases, ans, tiers["silver"])
        cells = [pct(metrics(cases, ans, tags[t])["accuracy"]) for t in tag_names]
        lines.append(f"| `{meta.get('label')}` | `{meta.get('commit') or '?'}` | {g['right']}/{g['n']} "
                     f"({pct(g['accuracy'])}) | {pct(g.get('weighted', {}).get('accuracy'))} | "
                     f"{s['right']}/{s['n']} ({pct(s['accuracy'])}) | " + " | ".join(cells) + " |")
    lines += ["", "Tag columns: accuracy on the cases carrying that failure trigger "
                  f"({', '.join(f'{t} {len(tags[t])}' for t in tag_names)}).", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(runs)} baseline(s) → {OUT.relative_to(HERE.parents[1])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
