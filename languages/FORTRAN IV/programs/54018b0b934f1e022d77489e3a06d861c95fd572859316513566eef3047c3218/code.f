C     FORTRAN IV PROGRAM TO COMPUTE FACTORIAL
C     CLASSIC EXAMPLE FROM 1960s
      INTEGER N, FACT, I
      READ(5,100) N
100   FORMAT(I5)
      FACT = 1
      IF (N .LE. 1) GO TO 300
      DO 200 I = 2, N
200   FACT = FACT * I
300   WRITE(6,400) N, FACT
400   FORMAT(1H ,I5,5H! = ,I10)
      STOP
      END
